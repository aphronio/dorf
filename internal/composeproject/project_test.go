func composeNetworkNames(t *testing.T, service string) []string {
	t.Helper()
	lines := strings.Split(service, "\n")
	for index, line := range lines {
		if line != "    networks:" {
			continue
		}
		var names []string
		for _, entry := range lines[index+1:] {
			if strings.HasPrefix(entry, "      - ") {
				names = append(names, strings.TrimSpace(strings.TrimPrefix(entry, "      - ")))
				continue
			}
			if strings.HasPrefix(entry, "      ") && !strings.HasPrefix(entry, "        ") && strings.HasSuffix(entry, ":") {
				names = append(names, strings.TrimSuffix(strings.TrimSpace(entry), ":"))
				continue
			}
			if strings.HasPrefix(entry, "        ") {
				continue
			}
			break
		}
		return names
	}
	t.Fatalf("service has no explicit networks:\n%s", service)
	return nil
}

func dotenvValue(t *testing.T, environment []byte, key string) string {
	t.Helper()
	prefix := key + "='"
	for _, line := range strings.Split(string(environment), "\n") {
		if strings.HasPrefix(line, prefix) && strings.HasSuffix(line, "'") {
			return strings.TrimSuffix(strings.TrimPrefix(line, prefix), "'")
		}
	}
	t.Fatalf("environment is missing %s:\n%s", key, environment)
	return ""
}

