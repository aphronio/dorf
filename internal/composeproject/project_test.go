	project := renderOptionalServicesProject(t)
	compose := string(project.Files[ComposeFile].Contents)
	services := []struct {
		name, next string
		want       []string
	}{
		{name: "postgres", next: "migrate", want: []string{"database"}},
		{name: "migrate", next: "worker", want: []string{"database"}},
		{name: "worker", next: "control-reader", want: []string{"application", "database", "worker-egress"}},
		{name: "control-reader", next: "control-api", want: []string{"database", "provider", "reader", "reader-egress"}},
		{name: "control-api", next: "provider-gateway", want: []string{"database", "reader"}},
		{name: "provider-gateway", next: "cloudflared", want: []string{"application", "ingress", "provider"}},
	}
	for _, service := range services {
		block := composeServiceBlock(t, compose, service.name, service.next)
		if got := composeNetworkNames(t, block); strings.Join(got, ",") != strings.Join(service.want, ",") {
			t.Fatalf("%s networks=%v want=%v\n%s", service.name, got, service.want, block)
		}
	}
	reader := composeServiceBlock(t, compose, "control-reader", "control-api")
	if !strings.Contains(reader, "          - control-reader-rpc") {
		t.Fatalf("control reader lacks reader-network-only DNS identity:\n%s", reader)
	}
	control := composeServiceBlock(t, compose, "control-api", "provider-gateway")
	if !strings.Contains(control, "condition: service_healthy") {
		t.Fatalf("control API does not wait for authenticated reader health:\n%s", control)
	}
