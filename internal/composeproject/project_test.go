func TestRenderGivesEachServiceOnlyItsRuntimeEnvironment(t *testing.T) {
	project := renderEnvironmentProject(t)
	compose := string(project.Files[ComposeFile].Contents)
	withLayout := func(keys ...string) []string {
		return append([]string{"XDG_CONFIG_HOME", "XDG_DATA_HOME", "XDG_STATE_HOME"}, keys...)
	}
	services := []struct {
		name string
		next string
		want []string
	}{
		{name: "postgres", next: "migrate", want: []string{"POSTGRES_DB", "POSTGRES_USER", "POSTGRES_PASSWORD"}},
		{name: "migrate", next: "worker", want: withLayout("DORF_DATABASE_URL")},
		{name: "worker", next: "control-reader", want: withLayout("DORF_DATABASE_URL", "E2B_API_KEY")},
		{name: "control-reader", next: "control-api", want: withLayout("DORF_DATABASE_URL", "DORF_CONTROL_READER_TOKEN", "E2B_API_KEY")},
	}
	for _, service := range services {
		t.Run(service.name, func(t *testing.T) {
			block := composeServiceBlock(t, compose, service.name, service.next)
			if strings.Contains(block, "env_file:") {
				t.Fatalf("service receives the whole protected project environment:\n%s", block)
			}
			if got := composeEnvironmentKeys(t, block); strings.Join(got, ",") != strings.Join(service.want, ",") {
				t.Fatalf("runtime environment keys=%v want=%v\n%s", got, service.want, block)
			}
			if service.name != "postgres" {
				assertFixedContainerXDGLayout(t, block)
			}
		})
	}
	t.Run("control-api", func(t *testing.T) {
		block := composeFinalServiceBlock(t, compose, "control-api")
		if strings.Contains(block, "env_file:") {
			t.Fatalf("service receives the whole protected project environment:\n%s", block)
		}
		want := withLayout("DORF_DATABASE_URL", "DORF_CONTROL_READER_ORIGIN", "DORF_CONTROL_READER_TOKEN")
		if got := composeEnvironmentKeys(t, block); strings.Join(got, ",") != strings.Join(want, ",") {
			t.Fatalf("runtime environment keys=%v want=%v\n%s", got, want, block)
		}
		assertFixedContainerXDGLayout(t, block)
	})
}

