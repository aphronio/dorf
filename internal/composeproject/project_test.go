func composeServiceBlock(t *testing.T, compose, service, nextService string) string {
	t.Helper()
	startMarker := "\n  " + service + ":\n"
	start := strings.Index(compose, startMarker)
	if start < 0 {
		t.Fatalf("missing Compose service %q", service)
	}
	start += len(startMarker)
	endMarker := "\n  " + nextService + ":\n"
	end := strings.Index(compose[start:], endMarker)
	if end < 0 {
		t.Fatalf("missing service %q after %q", nextService, service)
	}
	return compose[start : start+end]
}

