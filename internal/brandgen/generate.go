package brandgen

import (
	"bytes"
	"fmt"
	"go/format"
	"image"
	"image/color"
	_ "image/png"
	"io"
	"math"
	"strconv"
	"strings"
)

const (
	logoColumns     = 16
	logoRows        = 8
	wordmarkColumns = 34
	wordmarkRows    = 6
	wordmarkFill    = 0.50
)

type logoLine struct {
	Glyphs string
	Colors []uint32
}

type generatedBrand struct {
	Logo     []logoLine
	Wordmark []string
}

// Source derives the terminal lockup from the canonical raster assets and
// returns deterministic gofmt-formatted source for internal/brand.
func Source(logoReader, coverReader io.Reader) ([]byte, error) {
	logo, _, err := image.Decode(logoReader)
	if err != nil {
		return nil, fmt.Errorf("decode logo: %w", err)
	}
	cover, _, err := image.Decode(coverReader)
	if err != nil {
		return nil, fmt.Errorf("decode cover: %w", err)
	}
	brand, err := generate(logo, cover)
	if err != nil {
		return nil, err
	}

	var output bytes.Buffer
	output.WriteString("// Code generated by dorf-brand-terminal; DO NOT EDIT.\n\npackage brand\n\n")
	output.WriteString("var terminalLogo = []terminalLogoLine{\n")
	for _, line := range brand.Logo {
		fmt.Fprintf(&output, "\t{Glyphs: %s, Colors: []uint32{", strconv.Quote(line.Glyphs))
		for index, value := range line.Colors {
			if index > 0 {
				output.WriteString(", ")
			}
			fmt.Fprintf(&output, "0x%06X", value)
		}
		output.WriteString("}},\n")
	}
	output.WriteString("}\n\nvar terminalWordmark = []string{\n")
	for _, line := range brand.Wordmark {
		fmt.Fprintf(&output, "\t%s,\n", strconv.Quote(line))
	}
	output.WriteString("}\n")
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated terminal brand: %w", err)
	}
	return formatted, nil
}

func generate(logo, cover image.Image) (generatedBrand, error) {
	logoBounds, ok := visibleBounds(logo)
	if !ok {
		return generatedBrand{}, fmt.Errorf("logo has no visible pixels")
	}
	logoLines := make([]logoLine, logoRows)
	dots := resizeLogoDots(logo, logoBounds)
	for row := range logoRows {
		var glyphs strings.Builder
		colors := make([]uint32, logoColumns)
		for column := range logoColumns {
			code := brailleCode(dots, column*2, row*4)
			if code == 0 {
				glyphs.WriteRune(' ')
				continue
			}
			glyphs.WriteRune(rune(0x2800 + code))
			colors[column] = sampleLogoColor(logo, logoBounds, column, row)
		}
		logoLines[row] = logoLine{Glyphs: strings.TrimRight(glyphs.String(), " "), Colors: colors}
	}

	wordmarkBounds, ok := detectedWordmarkBounds(cover)
	if !ok {
		return generatedBrand{}, fmt.Errorf("cover has no detectable wordmark")
	}
	wordmark := resizeWordmark(cover, wordmarkBounds)
	return generatedBrand{Logo: logoLines, Wordmark: wordmark}, nil
}

func resizeLogoDots(source image.Image, bounds image.Rectangle) [][]bool {
	const dotColumns = logoColumns * 2
	const dotRows = logoRows * 4
	result := make([][]bool, dotRows)
	for y := range dotRows {
		result[y] = make([]bool, dotColumns)
		for x := range dotColumns {
			luminance, _ := sampleRegion(source, bounds, x, y, dotColumns, dotRows, false)
			result[y][x] = luminance >= 0.15
		}
	}
	return result
}

func brailleCode(dots [][]bool, x, y int) int {
	positions := [4][2]int{{1, 8}, {2, 16}, {4, 32}, {64, 128}}
	code := 0
	for dy, pair := range positions {
		for dx, value := range pair {
			if dots[y+dy][x+dx] {
				code += value
			}
		}
	}
	return code
}

func sampleLogoColor(source image.Image, bounds image.Rectangle, column, row int) uint32 {
	_, average := sampleRegion(source, bounds, column, row, logoColumns, logoRows, true)
	brighten := func(value uint8) uint8 {
		return uint8(min(255, int(value)*3/4+64))
	}
	return uint32(brighten(average.R))<<16 | uint32(brighten(average.G))<<8 | uint32(brighten(average.B))
}

func sampleRegion(source image.Image, bounds image.Rectangle, column, row, columns, rows int, visibleOnly bool) (float64, color.NRGBA) {
	x0 := bounds.Min.X + column*bounds.Dx()/columns
	x1 := bounds.Min.X + (column+1)*bounds.Dx()/columns
	y0 := bounds.Min.Y + row*bounds.Dy()/rows
	y1 := bounds.Min.Y + (row+1)*bounds.Dy()/rows
	if x1 <= x0 {
		x1 = x0 + 1
	}
	if y1 <= y0 {
		y1 = y0 + 1
	}
	var red, green, blue, alpha, luminance, samples float64
	for y := y0; y < y1; y++ {
		for x := x0; x < x1; x++ {
			pixel := color.NRGBAModel.Convert(source.At(x, y)).(color.NRGBA)
			weight := float64(pixel.A) / 255
			if visibleOnly && weight < 0.03 {
				continue
			}
			red += float64(pixel.R) * weight
			green += float64(pixel.G) * weight
			blue += float64(pixel.B) * weight
			alpha += weight
			luminance += (0.2126*float64(pixel.R) + 0.7152*float64(pixel.G) + 0.0722*float64(pixel.B)) / 255 * weight
			samples++
		}
	}
	if samples == 0 || alpha == 0 {
		return 0, color.NRGBA{}
	}
	return luminance / samples, color.NRGBA{R: uint8(math.Round(red / alpha)), G: uint8(math.Round(green / alpha)), B: uint8(math.Round(blue / alpha)), A: 255}
}

func visibleBounds(source image.Image) (image.Rectangle, bool) {
	bounds := source.Bounds()
	result := image.Rectangle{Min: bounds.Max, Max: bounds.Min}
	for y := bounds.Min.Y; y < bounds.Max.Y; y++ {
		for x := bounds.Min.X; x < bounds.Max.X; x++ {
			pixel := color.NRGBAModel.Convert(source.At(x, y)).(color.NRGBA)
			if pixel.A < 8 || int(max(pixel.R, pixel.G, pixel.B))*int(pixel.A)/255 < 2 {
				continue
			}
			result.Min.X = min(result.Min.X, x)
			result.Min.Y = min(result.Min.Y, y)
			result.Max.X = max(result.Max.X, x+1)
			result.Max.Y = max(result.Max.Y, y+1)
		}
	}
	return result, result.Min.X < result.Max.X && result.Min.Y < result.Max.Y
}

func detectedWordmarkBounds(source image.Image) (image.Rectangle, bool) {
	bounds := source.Bounds()
	search := image.Rect(
		bounds.Min.X+bounds.Dx()*3/5,
		bounds.Min.Y,
		bounds.Max.X,
		bounds.Min.Y+bounds.Dy()*2/5,
	)
	result := image.Rectangle{Min: search.Max, Max: search.Min}
	for y := search.Min.Y; y < search.Max.Y; y++ {
		for x := search.Min.X; x < search.Max.X; x++ {
			if !isWordmarkPixel(source.At(x, y)) {
				continue
			}
			result.Min.X = min(result.Min.X, x)
			result.Min.Y = min(result.Min.Y, y)
			result.Max.X = max(result.Max.X, x+1)
			result.Max.Y = max(result.Max.Y, y+1)
		}
	}
	return result, result.Min.X < result.Max.X && result.Min.Y < result.Max.Y
}

func resizeWordmark(source image.Image, bounds image.Rectangle) []string {
	cells := make([][]bool, wordmarkRows)
	for row := range wordmarkRows {
		cells[row] = make([]bool, wordmarkColumns)
		for column := range wordmarkColumns {
			x0 := bounds.Min.X + column*bounds.Dx()/wordmarkColumns
			x1 := bounds.Min.X + (column+1)*bounds.Dx()/wordmarkColumns
			y0 := bounds.Min.Y + row*bounds.Dy()/wordmarkRows
			y1 := bounds.Min.Y + (row+1)*bounds.Dy()/wordmarkRows
			matched, total := 0, 0
			for y := y0; y < max(y0+1, y1); y++ {
				for x := x0; x < max(x0+1, x1); x++ {
					total++
					if isWordmarkPixel(source.At(x, y)) {
						matched++
					}
				}
			}
			cells[row][column] = total > 0 && float64(matched)/float64(total) >= wordmarkFill
		}
	}
	pruneWordmarkCornerSpurs(cells)

	lines := make([]string, wordmarkRows)
	for row := range wordmarkRows {
		var line strings.Builder
		for column := range wordmarkColumns {
			if cells[row][column] {
				line.WriteRune('█')
			} else {
				line.WriteRune(' ')
			}
		}
		lines[row] = line.String()
	}
	return lines
}

// pruneWordmarkCornerSpurs removes a sub-cell corner that can become a full
// block when the cover wordmark is compressed. A genuine vertical stroke has
// another vertical neighbor; the cover's top-right f corner does not.
func pruneWordmarkCornerSpurs(cells [][]bool) {
	for row := 1; row < len(cells)-1; row++ {
		for column := range cells[row] {
			left := column > 0 && cells[row][column-1]
			right := column+1 < len(cells[row]) && cells[row][column+1]
			aboveLeft := column > 0 && cells[row-1][column-1]
			aboveRight := column+1 < len(cells[row]) && cells[row-1][column+1]
			if !cells[row][column] || left || right || cells[row+1][column] {
				continue
			}
			if cells[row-1][column] && (aboveLeft || aboveRight) {
				cells[row][column] = false
			}
		}
	}
}

func isWordmarkPixel(value color.Color) bool {
	pixel := color.NRGBAModel.Convert(value).(color.NRGBA)
	luminance := (2126*int(pixel.R) + 7152*int(pixel.G) + 722*int(pixel.B)) / 10_000
	return pixel.A >= 128 && luminance > 150 && pixel.R > pixel.G && pixel.G > pixel.B && int(pixel.R)-int(pixel.G) < 70 && int(pixel.G)-int(pixel.B) < 100
}
